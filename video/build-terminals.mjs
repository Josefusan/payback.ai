#!/usr/bin/env node
/**
 * Fold the real captured API transcripts into a classic script the scenes can include over file://.
 *
 * The strings produced here are byte-for-byte the response bodies written by `video/capture-api.sh`,
 * so a terminal panel in the film can never drift from what the live Worker actually returned.
 */
import fs from "node:fs";
import path from "node:path";

const HERE = import.meta.dirname;
const CAP = path.join(HERE, "captures");
const files = fs.readdirSync(CAP).filter((f) => f.startsWith("api-") && f.endsWith(".txt")).sort();

const out = {};
for (const file of files) {
  const name = file.replace(/\.txt$/, "");
  const raw = fs.readFileSync(path.join(CAP, file), "utf8").replace(/\s+$/, "");
  const lines = raw.split("\n");
  out[name] = { cmd: lines[0] ?? "", out: lines.slice(1).join("\n").trim() };
}

const banner = "/* GENERATED by video/build-terminals.mjs from video/captures/api-*.txt — do not hand-edit. */";
fs.writeFileSync(path.join(HERE, "terminals.js"), `${banner}\nwindow.PB_TERMS = ${JSON.stringify(out, null, 2)};\n`);
console.log(`wrote video/terminals.js (${Object.keys(out).length} transcripts: ${Object.keys(out).join(", ")})`);
